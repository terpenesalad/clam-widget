"""Generates the hidden-mode widget layouts that flip through the rat frames.

Each state is a ViewFlipper of ImageViews pointing at rat_<clip>_<nn> drawables.
Repeated clips reuse the same drawables, so memory is only the unique frames.
Run from the repo root:  python3 tools/make_rat_layouts.py
"""
import os, re

RES = "android/app/src/main/res"
FPS = 12
INTERVAL = round(1000 / FPS)

frames = {}
for f in os.listdir(f"{RES}/drawable-nodpi"):
    m = re.match(r"rat_(.+)_(\d+)\.(png|webp)$", f)
    if m:
        frames.setdefault(m.group(1), []).append(int(m.group(2)))
for k in frames:
    frames[k].sort()

def clip(name):
    return [f"rat_{name}_{i:02d}" for i in frames[name]]

B, ET, EP, NOD, SN, SH = "breathe", "ear_twitch", "ear_perk", "nod", "sneeze", "shake"
IDLE = [B, B, ET, B, B, NOD, B, EP, B, B, SN, B, B, SH, B, ET, B, EP, B, B]
HOLD = 18  # extra copies of a one-shot's last frame while the app swaps layouts

states = {
    "widget_rat_idle": sum((clip(c) for c in IDLE), []),
    "widget_rat_sleep_enter": clip("sleep_enter") + [clip("sleep_enter")[-1]] * HOLD,
    "widget_rat_sleep": clip("sleep_loop"),
    "widget_rat_wake": clip("wake") + [clip("wake")[-1]] * HOLD,
}

SHELL = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_rat_layouts.py -->
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@android:id/background"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:background="@drawable/widget_bg"
    android:orientation="horizontal"
    android:gravity="center_vertical"
    android:paddingStart="22dp"
    android:paddingEnd="10dp"
    android:paddingTop="6dp"
    android:paddingBottom="6dp">

    <FrameLayout
        android:layout_width="0dp"
        android:layout_height="match_parent"
        android:layout_weight="1">

        <ImageView
            android:layout_width="wrap_content"
            android:layout_height="22dp"
            android:layout_gravity="center_vertical|start"
            android:adjustViewBounds="true"
            android:scaleType="fitStart"
            android:src="@drawable/clam_logo"
            android:contentDescription="CLAM" />
    </FrameLayout>

    <ViewFlipper
        android:layout_width="0dp"
        android:layout_height="match_parent"
        android:layout_weight="1.25"
        android:autoStart="true"
        android:flipInterval="{interval}"
        android:measureAllChildren="false">
{children}
    </ViewFlipper>
</LinearLayout>
"""
CHILD = ('        <ImageView android:layout_width="match_parent" android:layout_height="match_parent" '
         'android:scaleType="fitCenter" android:src="@drawable/{0}" />')

for name, seq in states.items():
    xml = SHELL.replace("{interval}", str(INTERVAL)).replace(
        "{children}", "\n".join(CHILD.format(r) for r in seq))
    open(f"{RES}/layout/{name}.xml", "w").write(xml)
    print(f"{name}: {len(seq)} frames, {len(set(seq))} unique, {len(seq)/FPS:.1f}s")

# durations the app needs to know (ms) for chaining one-shots
dur = {k: round(len(clip(k)) * 1000 / FPS) for k in ("sleep_enter", "wake")}
open(f"{RES}/values/rat_timing.xml", "w").write(
    '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
    f'    <integer name="rat_sleep_enter_ms">{dur["sleep_enter"]}</integer>\n'
    f'    <integer name="rat_wake_ms">{dur["wake"]}</integer>\n</resources>\n')
print(dur)
